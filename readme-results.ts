// Regenerate the numbers block in README.md from data/evidence*.json (between the RESULTS markers).
//   npx tsx readme-results.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const load = (f: string) => existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : null;
const sets = [["Discovery", load("data/evidence.json")], ["Holdout", load("data/evidence_holdout.json")],
  ["Confirmation", load("data/evidence_confirm.json")]].filter(([, e]) => e) as [string, any][];
const all = load("data/evidence_all.json") ?? sets[0][1];
const cell = (s: any) => !s ? "–" : s.too_few ? `${s.alive}/${s.n} (too few)` : `${s.alive_pct}% (${s.alive}/${s.n.toLocaleString("en-GB")})`;

const s = all.summary;
let md = `<!-- RESULTS:START (generated by readme-results.ts from data/ - do not edit by hand) -->\n`;
md += `Snapshot ${s.snapshot.slice(0, 10)} · ${s.rows.toLocaleString("en-GB")} sampled DAMM v2 pools · ` +
  `${s.graduated.toLocaleString("en-GB")} SOL-quoted DBC graduates · **${s.spam_pct}% were instant-graduation spam** · ` +
  `${s.kept.toLocaleString("en-GB")} kept · **${s.self_serve.alive_pct}% of ${s.self_serve.n.toLocaleString("en-GB")} self-serve graduates still alive** (≥ $1k liquidity).\n\n`;
md += `| Self-serve launches still alive | ${sets.map(([n]) => n).join(" | ")} |\n|---|${sets.map(() => "---|").join("")}\n`;
md += `| All self-serve graduates (baseline) | ${sets.map(([, e]) => cell(e.summary.self_serve)).join(" | ")} |\n`;
for (const p of all.presetEvidence) md += `| Preset: ${p.preset} | ${sets.map(([, e]) => cell(e.presetEvidence.find((x: any) => x.preset === p.preset))).join(" | ")} |\n`;
for (const w of all.warningEvidence) md += `| Warning: ${w.text} | ${sets.map(([, e]) => cell(e.warningEvidence.find((x: any) => x.id === w.id))).join(" | ")} |\n`;
md += `\nRules were chosen on Discovery, frozen, then measured on the other samples. Full tables: RESULTS*.md.\n<!-- RESULTS:END -->`;

const readme = readFileSync("README.md", "utf8");
writeFileSync("README.md", readme.replace(/<!-- RESULTS:START[\s\S]*?<!-- RESULTS:END -->/, md));
